/// Days since the unix epoch for a civil date (Hinnant's `days_from_civil`,
/// the inverse of `kostats::ymd`).
fn civil((y, m, d): (i64, i64, i64)) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// A stated page count for one day of one read: none on two days in seven.
fn pages_on(day: i64, book: i64) -> i64 {
    let h = (day.wrapping_mul(2_654_435_761) ^ book.wrapping_mul(40_503)).rem_euclid(1 << 31);
    if h % 7 < 2 { 0 } else { 6 + h % 31 }
}

/// History's reads, their passages, notes, rated reviews and **measured
/// days** (2026-11-10). Returns how many notes it added.
///
/// The measured days are written as `reading_events` rows, `source =
/// 'koreader'`, `confidence = 'measured'` — what `import_device_statistics`
/// writes from a reader's `statistics.sqlite3`. That is the one table the
/// Makefile otherwise leaves to the engine's own fillers, and the exception
/// is deliberate: pages and minutes are **origin data** (a device measured
/// them), not a derivation of anything else in the seed, and no device-free
/// filler can produce them. `make dev-db`'s refill then merges its inferred
/// rows into these with `EVENT_MERGE`'s no-clobber rule, exactly as it would
/// after a real statistics import.
fn history(
    sql: &mut String,
    vault: &Path,
    books: &[Book],
    mut reading_id: i64,
    mut note_id: i64,
    mut highlight_id: i64,
) -> std::io::Result<usize> {
    let today = civil(HISTORY_TODAY);
    let mut written = 0;
    for (book, r) in books.iter().zip(HISTORY) {
        reading_id += 1;
        let (title, _, pages, started, ended, kind, rating, passages, notes) = *r;
        let start_day = civil(started);
        let start = start_day * DAY + 9 * 3_600;
        let end = ended.map(|e| civil(e) * DAY + 21 * 3_600);
        let (status, finished_at, put_down_at, page) = match kind {
            HistoryKind::Read => ("finished", end, None, Some(pages)),
            HistoryKind::Reading => ("reading", None, None, Some(pages * 2 / 3)),
            // The 2025 one predates `0025`: no instant, and the engine must say
            // *not recorded* rather than invent one.
            HistoryKind::PutDown => (
                "abandoned",
                None,
                if started.0 >= 2026 { end } else { None },
                Some(pages / 3),
            ),
        };
        let opt = |v: Option<i64>| v.map(|x| x.to_string()).unwrap_or("NULL".into());
        let touched = end.unwrap_or(today * DAY);
        sql.push_str(&format!(
            "INSERT INTO readings (id, book_id, started_at, finished_at, status, source, \
             current_page, ko_status, ko_percent, ko_rating, created_at, last_modified, put_down_at) \
             VALUES ({reading_id}, {}, {start}, {}, '{status}', 'koreader', {}, NULL, NULL, NULL, \
             {start}, {touched}, {});\n",
            book.id,
            opt(finished_at),
            opt(page),
            opt(put_down_at),
        ));

        let last_day = end.map_or(today, |e| e.div_euclid(DAY)).min(today);
        let span_days = (last_day - start_day + 1).max(1);
        // The measured days.
        for day in start_day..=last_day {
            let p = pages_on(day, book.id);
            if p == 0 {
                continue;
            }
            sql.push_str(&format!(
                "INSERT INTO reading_events (book_id, reading_id, day, minutes, pages, source, \
                 confidence, created_at) VALUES ({}, {reading_id}, {}, {}, {p}, 'koreader', \
                 'measured', {});\n",
                book.id,
                q(&crate::kostats::ymd(day)),
                p * 17 / 10,
                day * DAY,
            ));
        }
        // Passages, spread over the read's days and attributed to it.
        for k in 0..passages as i64 {
            highlight_id += 1;
            let at =
                (start_day + (2 * k + 1) * span_days / (2 * passages as i64)) * DAY + 20 * 3_600;
            let datetime = format!(
                "{} {:02}:{:02}:00",
                crate::kostats::ymd(at.div_euclid(DAY)),
                at.rem_euclid(DAY) / 3_600,
                at.rem_euclid(3_600) / 60,
            );
            let text = format!("{}.", PHRASES[(highlight_id as usize) % PHRASES.len()]);
            let mut hasher = Sha256::new();
            hasher.update(format!("{}|{datetime}||{text}", book.id));
            sql.push_str(&format!(
                "INSERT INTO highlights (id, book_id, reading_id, text, chapter, page, ko_datetime, \
                 color, origin_note, annotation, source, identity_hash, created_at) VALUES \
                 ({highlight_id}, {}, {reading_id}, {}, NULL, {}, {}, 'yellow', NULL, NULL, \
                 'koreader', {}, {at});\n",
                book.id,
                q(&text),
                1 + (k * 23) % pages,
                q(&datetime),
                q(&hex(&hasher.finalize())),
            ));
        }
        // Ordinary notes written during the read (placed by their date), and
        // a rated review on every rated read.
        let mut seeded: Vec<(String, &'static str, Option<i64>, String, i64)> = (0..notes as i64)
            .map(|k| {
                let at = (start_day + (k + 1) * span_days / (notes as i64 + 1)) * DAY + 22 * 3_600;
                (
                    format!("{} — a thought ({})", display_title(title), k + 1),
                    "note",
                    None,
                    format!(
                        "Something in {} I want to keep, the {}th time.",
                        display_title(title),
                        k + 1
                    ),
                    at,
                )
            })
            .collect();
        if rating.is_some() {
            seeded.push((
                format!("Review: {}", display_title(title)),
                "review",
                Some(reading_id),
                "Written for other people.".into(),
                end.unwrap_or(start),
            ));
        }
        for (note_title, kind, read, body, at) in seeded {
            note_id += 1;
            let path = format!("{:04}-{}.md", note_id, slug(&note_title));
            std::fs::write(vault.join(&path), format!("{body}\n"))?;
            sql.push_str(&format!(
                "INSERT INTO notes (id, book_id, reading_id, highlight_id, page, file_path, title, \
                 kind, created_at, last_modified, parts, latest_part_at) VALUES \
                 ({note_id}, {}, {}, NULL, NULL, {}, {}, '{kind}', {at}, {at}, 1, {at});\n",
                book.id,
                opt(read),
                q(&path),
                q(&note_title),
            ));
            sql.push_str(&format!(
                "INSERT INTO notes_fts (rowid, title, body) VALUES ({note_id}, {}, {});\n",
                q(&note_title),
                q(&body)
            ));
            if kind == "review" {
                sql.push_str(&format!(
                    "INSERT INTO review_ratings (note_id, scale_id, value) \
                     SELECT {note_id}, id, {:.1} FROM rating_scales WHERE name = 'default';\n",
                    rating.unwrap_or_default()
                ));
            }
            written += 1;
        }
    }
    Ok(written)
}

